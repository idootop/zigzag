//! 去重。
//!
//! 和压缩是**两件独立的事**，不共用一条流水线：压缩替换文件、去重删除文件，
//! 两者不可逆的方式不一样，风险也不一样，混在一个「开始」按钮后面等于让用户
//! 用一次点击同时授权两种破坏。
//!
//! 分两层，判据强度不同，因而处置方式也不同：
//!
//! - [`exact`]：字节完全相同。判断是确定的，可以放心批量处理。
//! - [`perceptual`]：看起来像。判断是概率性的，**必须人来点头**
//!   ——一组连拍在感知哈希眼里几乎一样，但它们是五张不同的照片。
//!
//! 两层都把「算过的哈希」交给 [`cache`]，那也就是「续跑」的全部实现。

pub mod apply;
